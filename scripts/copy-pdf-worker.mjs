// Cross-Origin Isolation probe worker (authored here — the only source of
// truth; public/tesseract/ is gitignored and fully provisioned).
//
// Mirrors the construction type and origin of the tesseract.js OCR worker —
// a classic same-origin dedicated worker served from /tesseract/*. Dedicated
// workers inherit their creator's agent-cluster isolation, so
// `self.crossOriginIsolated` here is exactly the property the OCR pipeline
// needs for SharedArrayBuffer-based transfers. It must be a static
// same-origin file because the app's Trusted Types default policy refuses
// blob:/data: script URLs by design (see
// src/components/security/TrustedTypesGate.tsx) — the same constraint
// tesseract.js satisfies with worker.min.js.
//
// Loaded only by e2e/coi-isolation.mjs: no OCR model bytes are loaded and
// no OCR inference runs — the probe only reports isolation state.
const coiProbeSource = `/*
 * Cross-Origin Isolation probe worker (OCR worker context).
 *
 * Generated by scripts/copy-pdf-worker.mjs (postinstall) — edit the script,
 * not this file. Served from /tesseract/* like the tesseract.js OCR worker
 * itself; a classic same-origin dedicated worker inherits its creator's
 * agent-cluster isolation, so this reports exactly the isolation state the
 * OCR pipeline depends on. Loaded only by e2e/coi-isolation.mjs.
 */
self.onmessage = () => {
  self.postMessage({
    crossOriginIsolated: self.crossOriginIsolated === true,
    sharedArrayBuffer: typeof SharedArrayBuffer !== "undefined",
  });
};
`;
fs.writeFileSync(path.join(ocrDir, "coi-probe.js"), coiProbeSource);
console.log(`Wrote COI probe worker to ${path.join(ocrDir, "coi-probe.js")}`);

// Worker-realm Trusted Types bootstrap for browser-local OCR (authored here —
// the only source of truth; public/tesseract/ is gitignored and fully
// provisioned).
//
// Production CSP enforces `require-trusted-types-for 'script'` with a
// `trusted-types ... default ...` allowlist, and the /tesseract/* assets are
// served with that same policy. A dedicated worker realm does NOT inherit the
// document's policy object, so the pinned tesseract.js worker — which loads
// its WASM core with `importScripts(corePath)` from a plain string — is
// refused by its own realm's Trusted Types enforcement. This guard installs
// the same strict `default` policy the document uses (same-origin, /tesseract/
// script URLs only; createScript/createHTML refused), then imports the pinned
// worker script. Browsers without Trusted Types skip the policy and
// importScripts behaves exactly as before. The OCR worker is spawned with
// `workerBlobURL: false` so the library never wraps this path in a blob (the
// document policy would refuse that).
const workerGuardSource = `/*
 * Trusted Types bootstrap for the browser-local OCR worker realm.
 *
 * Generated by scripts/copy-pdf-worker.mjs (postinstall) — edit the script,
 * not this file.
 *
 * This worker is spawned as the Tesseract worker (workerBlobURL: false) and
 * forwards to the pinned tesseract.js worker script after installing a
 * realm-local \`default\` policy. The policy mirrors the document policy in
 * src/lib/security/trusted-types-policy.ts, narrowed to the self-hosted OCR
 * asset directory: /tesseract/* script URLs on this origin only.
 */
(function () {
  "use strict";

  var factory = self.trustedTypes;
  if (factory && !factory.defaultPolicy) {
    try {
      factory.createPolicy("default", {
        createScriptURL: function (input) {
          var url = new URL(String(input), self.location.href);
          var isHttp = url.protocol === "https:" || url.protocol === "http:";
          if (isHttp && url.origin === self.location.origin && url.pathname.indexOf("/tesseract/") === 0) {
            return input;
          }
          throw new Error(
            "Trusted Types: refused non-OCR script URL (" + String(input).slice(0, 80) + ")",
          );
        },
        createScript: function () {
          throw new Error("Trusted Types: createScript is not permitted by the worker default policy");
        },
        createHTML: function () {
          throw new Error("Trusted Types: createHTML is not permitted by the worker default policy");
        },
      });
    } catch (err) {
      // Surface the failure at the importScripts sink below (a clear Trusted
      // Types refusal) instead of aborting before the worker registers its
      // message handler, which would hang the parent's initialization.
    }
  }

  // Convert transferred page bitmaps to encoded bytes OFF the page's main
  // thread. Stop the original event before the pinned Tesseract handler sees
  // it, then redispatch its exact protocol packet with the encoded image.
  self.addEventListener("message", async function (event) {
    var packet = event.data;
    var image = packet && packet.payload && packet.payload.image;
    if (!(image instanceof ImageBitmap)) return;
    event.stopImmediatePropagation();
    var canvas;
    try {
      canvas = new OffscreenCanvas(image.width, image.height);
      var context = canvas.getContext("2d");
      if (!context) throw new Error("OCR image context unavailable");
      context.drawImage(image, 0, 0);
      var blob = await canvas.convertToBlob({ type: "image/png" });
      packet.payload.image = new Uint8Array(await blob.arrayBuffer());
      self.dispatchEvent(new MessageEvent("message", { data: packet }));
    } catch (_) {
      // Fixed diagnostic only: document contents never appear in worker logs.
      self.postMessage({ workerId: packet.workerId, jobId: packet.jobId,
        action: packet.action, status: "reject", data: "OCR image preparation failed" });
    } finally {
      image.close();
      if (canvas) { canvas.width = 0; canvas.height = 0; }
    }
  }, true);
  importScripts("/tesseract/worker.min.js");
})();
`;
fs.writeFileSync(path.join(ocrDir, "worker-guard.js"), workerGuardSource);
console.log(`Wrote OCR worker guard to ${path.join(ocrDir, "worker-guard.js")}`);
