// Cross-Origin Isolation probe worker (authored here — the only source of
// truth; public/tesseract/ is gitignored and fully provisioned).
//
// Mirrors the construction type and origin of the tesseract.js OCR worker —
// a classic same-origin dedicated worker served from /tesseract/*. Dedicated
// workers inherit their creator's agent-cluster isolation, so
// `self.crossOriginIsolated` here is exactly the property the OCR pipeline
// needs for SharedArrayBuffer-based transfers. It must be a static
// same-origin file because the app's Trusted Types default policy refuses
// blob:/data: script URLs by design (see
// src/components/security/TrustedTypesGate.tsx) — the same constraint
// tesseract.js satisfies with worker.min.js.
//
// Loaded only by e2e/coi-isolation.mjs: no OCR model bytes are loaded and
// no OCR inference runs — the probe only reports isolation state.
const coiProbeSource = `/*
 * Cross-Origin Isolation probe worker (OCR worker context).
 *
 * Generated by scripts/copy-pdf-worker.mjs (postinstall) — edit the script,
 * not this file. Served from /tesseract/* like the tesseract.js OCR worker
 * itself; a classic same-origin dedicated worker inherits its creator's
 * agent-cluster isolation, so this reports exactly the isolation state the
 * OCR pipeline depends on. Loaded only by e2e/coi-isolation.mjs.
 */
self.onmessage = () => {
  self.postMessage({
    crossOriginIsolated: self.crossOriginIsolated === true,
    sharedArrayBuffer: typeof SharedArrayBuffer !== "undefined",
  });
};
`;
fs.writeFileSync(path.join(ocrDir, "coi-probe.js"), coiProbeSource);
console.log(`Wrote COI probe worker to ${path.join(ocrDir, "coi-probe.js")}`);
